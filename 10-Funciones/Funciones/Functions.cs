// La clase Functions sirve para demostrar la sobrecarga de funciones
//

class Functions
{
    public static int Suma (int a, int b)
    {
        return a + b;
    }

    public static double Suma (double a, double b)
    {
        return a + b;
    }

    public static string Suma(string a, string b)
    {
        return a + b;
    }
}
